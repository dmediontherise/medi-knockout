// Helper to convert NES palette index (0x00 - 0x3F) to [r, g, b, a]
export function nesToRgba(index: number): [number, number, number, number] {
  const clamped = Math.max(0, Math.min(63, index));
  const [r, g, b] = NES_PALETTE[clamped];
  return [r, g, b, 255];
}

// Check if a number is a valid NES palette index (0..63)
export function isNesIndex(index: number): boolean {
  return typeof index === 'number' && Number.isInteger(index) && index >= 0 && index <= 63;
}

// Helper to check if [r, g, b] or an index matches an entry in the NES palette
export function isNesColor(rOrIndex: number, g?: number, b?: number): boolean {
  if (g === undefined || b === undefined) {
    return isNesIndex(rOrIndex);
  }
  return NES_PALETTE.some(([pr, pg, pb]) => pr === rOrIndex && pg === g && pb === b);
}

// Maps every opponent color to a lighter NES entry (+0x10 within the same hue column, white stays white)
export function toFlashPalette(colorIndex: number): number {
  if (colorIndex < 0 || colorIndex > 63) return colorIndex;
  // White colors in NES palette: 0x20, 0x30 stay white
  if (colorIndex === 0x20 || colorIndex === 0x30) return colorIndex;
  const row = Math.floor(colorIndex / 16);
  const col = colorIndex % 16;
  if (row < 3) {
    return (row + 1) * 16 + col;
  }
  return colorIndex;
}

// Maps to a darker entry (-0x10, floor 0x0F)
export function toDarkPalette(colorIndex: number): number {
  if (colorIndex < 0 || colorIndex > 63) return colorIndex;
  const row = Math.floor(colorIndex / 16);
  const col = colorIndex % 16;
  if (row > 0) {
    return (row - 1) * 16 + col;
  }
  return 0x0f;
}

